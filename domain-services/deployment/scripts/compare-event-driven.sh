#!/usr/bin/env bash
# Compares the event-driven build (005) with the 004 build re-measured on the same host and profiles
# (005 research R11, FR-025, SC-011), and writes reports/event-driven/COMPARISON.md.
#
# Usage: compare-event-driven.sh [--reports DIR] [--out FILE]
#
# Reads report-*.json in event-driven/{baseline-004/default, baseline-004/stress, default, stress}
# with the reconciliation-<ts>.txt of the same timestamp. Every run is listed with its errors; every
# run of a profile counts toward its median. No improvement target is evaluated: deltas are
# reported as measured. Requires bash and jq.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
reports="$here/../reports/event-driven"
out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --reports) reports="$2"; shift 2 ;;
    --out) out="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
out="${out:-$reports/COMPARISON.md}"
command -v jq >/dev/null || { echo "jq is required" >&2; exit 2; }
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

collect() { # build profile dir
  local report ts rec recon
  for report in "$reports/$3"/report-*.json; do
    [ -e "$report" ] || continue
    ts="$(basename "$report" .json)"; ts="${ts#report-}"
    rec="$reports/$3/reconciliation-$ts.txt"
    recon="MISSING"
    [ -f "$rec" ] && recon="$(grep -E 'RECONCILIATION (PASS|FAIL)' "$rec" | tail -1 | tr -d '\r')"
    jq -c --arg build "$1" --arg profile "$2" --arg ts "$ts" --arg file "$3/$(basename "$report")" --arg recon "${recon:-NO RESULT}" '
      (.operations | map({key: .operation, value: .}) | from_entries) as $ops |
      {build: $build, profile: $profile, ts: $ts, file: $file,
       stations: .config.stations, duration: .config.durationSecondsRequested, wall: .wallClockSeconds,
       transactions: .totalTransactions, scans: $ops.SCAN_ITEM.successCount,
       throughput: ($ops.SCAN_ITEM.successCount / .wallClockSeconds),
       scanMean: $ops.SCAN_ITEM.meanMs, scanP95: $ops.SCAN_ITEM.p95Ms, scanP99: $ops.SCAN_ITEM.p99Ms,
       startP95: $ops.START_TRANSACTION.p95Ms,
       completeMean: $ops.COMPLETE_TRANSACTION.meanMs, completeP95: $ops.COMPLETE_TRANSACTION.p95Ms,
       completeP99: $ops.COMPLETE_TRANSACTION.p99Ms,
       operations: ([.operations[] | .successCount + .errorCount] | add),
       errors: ([.operations[].errorCount] | add),
       errorsByOp: ([.operations[] | select(.errorCount > 0) | "\(.operation) \(.errorCount)"] | join(", ")),
       recon: $recon}' "$report" | tr -d '\r'
  done
}
{
  collect 004 default baseline-004/default; collect 004 stress baseline-004/stress
  collect 005 default default; collect 005 stress stress
} > "$work/runs.jsonl"
[ -s "$work/runs.jsonl" ] || { echo "no reports found under $reports" >&2; exit 1; }

jq -rs '
  def r1: if . == null then "n/a" else ((. * 10 | round) / 10 | tostring) end;
  def median: sort | if length == 0 then null elif length % 2 == 1 then .[length / 2 | floor]
                     else (.[length / 2 - 1] + .[length / 2]) / 2 end;
  def med($b; $p; f): [.[] | select(.build == $b and .profile == $p) | f] | median;
  def delta($a; $b): if $a == null or $b == null or $a == 0 then "n/a" else "\((($b - $a) / $a * 1000 | round) / 10)%" end;
  . as $runs |
  "# Event-driven (005) versus 004, same host and profiles",
  "",
  "Generated by `domain-services/deployment/scripts/compare-event-driven.sh`. Profiles: **default** is the",
  "unchanged client with no workload flags (10 stations x 60 s); **stress** is `--stations=100 --duration=120`.",
  "Every measured run is listed; none is dropped. No improvement target is evaluated (005 research R11).",
  "",
  "## Runs",
  "",
  "| Build | Profile | Report | Transactions | Successful scans | Scans/s | Scan mean / p95 / p99 (ms) | Start p95 | Complete mean / p95 / p99 (ms) | Errors | Reconciliation |",
  "|---|---|---|---:|---:|---:|---|---:|---|---|---|",
  ($runs | sort_by(.build, .profile, .ts)[] |
    "| \(.build) | \(.profile) | `\(.file)` | \(.transactions) | \(.scans) | \(.throughput | r1) | \(.scanMean | r1) / \(.scanP95 | r1) / \(.scanP99 | r1) | \(.startP95 | r1) | \(.completeMean | r1) / \(.completeP95 | r1) / \(.completeP99 | r1) | \(.errors)\(if .errorsByOp != "" then " (\(.errorsByOp))" else "" end) | \(.recon) |"),
  "",
  "## Medians",
  "",
  "| Metric | 004 default | 005 default | Change | 004 stress | 005 stress | Change |",
  "|---|---:|---:|---:|---:|---:|---:|",
  ( [ ["Scan p95 (ms)", "scanP95"], ["Scan p99 (ms)", "scanP99"], ["Successful scans/s", "throughput"],
      ["Start p95 (ms)", "startP95"], ["Complete p95 (ms)", "completeP95"], ["Complete p99 (ms)", "completeP99"] ][] as [$label, $f] |
    (med("004"; "default"; .[$f])) as $a | (med("005"; "default"; .[$f])) as $b |
    (med("004"; "stress"; .[$f])) as $c | (med("005"; "stress"; .[$f])) as $d |
    "| \($label) | \($a | r1) | \($b | r1) | \(delta($a; $b)) | \($c | r1) | \($d | r1) | \(delta($c; $d)) |"),
  "| Runs | \([.[] | select(.build == "004" and .profile == "default")] | length) | \([.[] | select(.build == "005" and .profile == "default")] | length) | | \([.[] | select(.build == "004" and .profile == "stress")] | length) | \([.[] | select(.build == "005" and .profile == "stress")] | length) | |",
  "| Errors (all runs) | \([.[] | select(.build == "004" and .profile == "default") | .errors] | add // 0) | \([.[] | select(.build == "005" and .profile == "default") | .errors] | add // 0) | | \([.[] | select(.build == "004" and .profile == "stress") | .errors] | add // 0) | \([.[] | select(.build == "005" and .profile == "stress") | .errors] | add // 0) | |",
  "",
  "## Success rate (SC-002, SC-003)",
  "",
  ( ["default", "stress"][] as $p | [.[] | select(.build == "005" and .profile == $p)] as $r |
    "- 005 \($p): \($r | map(.operations) | add // 0) operations, \($r | map(.errors) | add // 0) errors" +
    (if ($r | map(.operations) | add // 0) > 0 then " (\(((1 - (($r | map(.errors) | add) / ($r | map(.operations) | add))) * 100000 | round) / 1000)% succeeded)" else "" end) + ".")
' "$work/runs.jsonl" | tr -d '\r' > "$out"
echo "wrote $out"
